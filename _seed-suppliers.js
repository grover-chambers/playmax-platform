/**
 * Generate SQL migration to seed 9 category supplier files into Supabase.
 * Run: node _seed-suppliers.js
 * Output: supabase/migrations/025_seed_supplier_files.sql
 */
const XLSX = require('xlsx');
const fs = require('fs');
const path = require('path');

const DATA_DIR = path.join(__dirname, '..', 'playmax-platform-master', 'Data');

// Read all 9 supplier files
const files = fs.readdirSync(DATA_DIR).filter(f => f.endsWith('SUPPLIERS.xlsx')).sort();
const allRows = [];

for (const f of files) {
  const wb = XLSX.readFile(path.join(DATA_DIR, f));
  const ws = wb.Sheets[wb.SheetNames[0]];
  const rows = XLSX.utils.sheet_to_json(ws);
  for (const row of rows) {
    const stockCode = String(row['Stock ID Code'] || row['STOCK CODE'] || '').trim();
    const itemName = String(row['Item Description'] || row['ITEM NAME'] || '').trim();
    const category = String(row['Category'] || row['CATEGORY'] || '').trim();
    const packSize = String(row['Pack Size'] || row['ALLOCATION/PACKAGING'] || '').trim();
    const supplierCode = String(row['Supplier Code'] || row['SUPPLIER CODE'] || '').trim();
    const supplierName = String(row['Supplier Name'] || row['SUPPLIER NAME'] || '').trim();
    if (stockCode && supplierName) {
      allRows.push({ stockCode, itemName, category, packSize, supplierCode, supplierName });
    }
  }
}

// Category mapping: supplier file category -> DB category name
// Migration 008 seeded these exact names; migration 023 added variants.
// We match against BOTH using ILIKE patterns.
const catMapping = {
  'COOKING OIL & FATS': 'COOKING OIL & FATS',  // exact match in migration 008
  'DIAPER': 'DIAPER',                           // exact match in migration 008
  'HONEY,JAM & SPREADS': 'HONEY, JAM & SPREADS', // migration 008 has space
  'MAIZE FLOUR': 'MAIZE FLOUR',                 // exact match in migration 008
  'RICE': 'RICE',
  'SNACKS': 'SNACKS',
  'SPICES': 'SPICES',                           // exact match in migration 008
  'SUGAR': 'SUGAR',
  'WHEAT FLOUR': 'WHEAT FLOUR',                 // exact match in migration 008
};

// No sub-category mapping needed — MAIZE FLOUR and WHEAT FLOUR are top-level categories
// in migration 008, not sub-categories of FLOUR.

// Deduplicate products by stock code
const products = new Map();
for (const r of allRows) {
  if (!products.has(r.stockCode)) products.set(r.stockCode, r);
}

// Unique suppliers
const suppliers = new Map();
for (const r of allRows) {
  if (!suppliers.has(r.supplierName)) {
    suppliers.set(r.supplierName, { name: r.supplierName, code: r.supplierCode });
  }
}

function esc(s) {
  return String(s).replace(/'/g, "''");
}

// Build SQL
const lines = [];
const w = (s) => lines.push(s);

w('-- =================================================================');
w('-- Migration 025: Seed 9 category supplier files');
w('-- ' + products.size + ' products, ' + suppliers.size + ' suppliers, ' + allRows.length + ' product-supplier links');
w('-- Generated by _seed-suppliers.js');
w('-- =================================================================');
w('BEGIN;');
w('');
w('-- 2. Suppliers (' + suppliers.size + ')');
w('INSERT INTO analytics_suppliers (name, code, active) VALUES');

const supArr = [...suppliers.values()];
for (let i = 0; i < supArr.length; i++) {
  const s = supArr[i];
  const comma = i < supArr.length - 1 ? ',' : '';
  w("  ('" + esc(s.name) + "', '" + esc(s.code) + "', true)" + comma);
}
w('ON CONFLICT (name) DO NOTHING;');
w('');

// Products — batch DO blocks
w('-- 3. Products (' + products.size + ')');
const prodArr = [...products.values()];
const BATCH = 100;

// Compact approach: single DO block per batch with VALUES list
for (let b = 0; b < prodArr.length; b += BATCH) {
  const batch = prodArr.slice(b, b + BATCH);
  w('DO $$ DECLARE');
  w('  cat_id uuid;');
  w('  r record;');
  w('BEGIN');
  w('  FOR r IN SELECT * FROM (VALUES');
  for (let i = 0; i < batch.length; i++) {
    const p = batch[i];
    const catName = catMapping[p.category] || p.category;
    const comma = i < batch.length - 1 ? ',' : '';
    w("    ('" + esc(p.stockCode) + "', '" + esc(p.itemName) + "', '" + esc(catName) + "', '" + esc(p.category) + "', '" + esc(p.packSize) + "')" + comma);
  }
  w('  ) AS t(stock_code, name, cat_name, sub_category, pack_size) LOOP');
  w("    SELECT id INTO cat_id FROM analytics_categories WHERE name = r.cat_name LIMIT 1;");
  w("    INSERT INTO analytics_products (stock_code, name, category_id, sub_category_id, sub_category, pack_size)");
  w("    VALUES (r.stock_code, r.name, cat_id, NULL, r.sub_category, r.pack_size)");
  w("    ON CONFLICT (stock_code) DO UPDATE SET");
  w("      name = EXCLUDED.name,");
  w("      category_id = COALESCE(EXCLUDED.category_id, analytics_products.category_id),");
  w("      sub_category_id = COALESCE(EXCLUDED.sub_category_id, analytics_products.sub_category_id),");
  w("      pack_size = COALESCE(EXCLUDED.pack_size, analytics_products.pack_size);");
  w('  END LOOP;');
  w('END $$;');
  w('');
}

// Supplier-Product junction links — compact VALUES list
w('-- 4. Supplier-Product links (' + allRows.length + ')');
for (let b = 0; b < allRows.length; b += BATCH) {
  const batch = allRows.slice(b, b + BATCH);
  w('DO $$ DECLARE');
  w('  sup_id uuid;');
  w('  prod_id uuid;');
  w('  r record;');
  w('BEGIN');
  w('  FOR r IN SELECT * FROM (VALUES');
  for (let i = 0; i < batch.length; i++) {
    const r = batch[i];
    const comma = i < batch.length - 1 ? ',' : '';
    w("    ('" + esc(r.supplierName) + "', '" + esc(r.stockCode) + "', '" + esc(r.packSize) + "')" + comma);
  }
  w('  ) AS t(sup_name, stock_code, pack_size) LOOP');
  w("    SELECT id INTO sup_id FROM analytics_suppliers WHERE name = r.sup_name LIMIT 1;");
  w("    SELECT id INTO prod_id FROM analytics_products WHERE stock_code = r.stock_code LIMIT 1;");
  w('    IF sup_id IS NOT NULL AND prod_id IS NOT NULL THEN');
  w("      INSERT INTO analytics_supplier_products (supplier_id, product_id, pack_size)");
  w("      VALUES (sup_id, prod_id, r.pack_size)");
  w('      ON CONFLICT DO NOTHING;');
  w('    END IF;');
  w('  END LOOP;');
  w('END $$;');
  w('');
}

w('COMMIT;');

// Write migration
const outPath = path.join(__dirname, 'supabase', 'migrations', '025_seed_supplier_files.sql');
fs.writeFileSync(outPath, lines.join('\n'));
console.log('Written: ' + outPath);
console.log('Lines: ' + lines.length);
console.log('Products: ' + products.size);
console.log('Suppliers: ' + suppliers.size);
console.log('Links: ' + allRows.length);
